CREATE TABLE IF NOT EXISTS dim_tempo (
    tempo_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_calendario DATE NOT NULL UNIQUE,
    ano SMALLINT NOT NULL,
    numero_mes SMALLINT NOT NULL CHECK (numero_mes BETWEEN 1 AND 12),
    nome_mes VARCHAR(12) NOT NULL,
    trimestre SMALLINT NOT NULL CHECK (trimestre BETWEEN 1 AND 4),
    numero_dia SMALLINT NOT NULL CHECK (numero_dia BETWEEN 1 AND 31),
    dia_semana_numero SMALLINT NOT NULL CHECK (dia_semana_numero BETWEEN 1 AND 7),
    CHECK (ano = EXTRACT(YEAR FROM data_calendario)),
    CHECK (numero_mes = EXTRACT(MONTH FROM data_calendario)),
    CHECK (numero_dia = EXTRACT(DAY FROM data_calendario))
);

CREATE TABLE IF NOT EXISTS dim_secao_produto (
    secao_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_secao VARCHAR(10) NOT NULL UNIQUE,
    nome_secao TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS fato_exportacao_mensal (
    tempo_id INTEGER NOT NULL REFERENCES dim_tempo(tempo_id),
    secao_id INTEGER NOT NULL REFERENCES dim_secao_produto(secao_id),
    valor_fob_usd NUMERIC(20, 2) NOT NULL CHECK (valor_fob_usd >= 0),
    quilograma_liquido NUMERIC(24, 3) NOT NULL CHECK (quilograma_liquido >= 0),
    PRIMARY KEY (tempo_id, secao_id)
);

CREATE TABLE IF NOT EXISTS etl_execucao (
    execucao_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fonte_atualizada_em DATE NOT NULL,
    periodo_inicio DATE NOT NULL,
    periodo_fim DATE NOT NULL,
    arquivo_bruto TEXT NOT NULL,
    linhas_carregadas INTEGER NOT NULL CHECK (linhas_carregadas >= 0),
    executado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (periodo_inicio <= periodo_fim)
);

CREATE INDEX IF NOT EXISTS ix_fato_exportacao_secao
    ON fato_exportacao_mensal (secao_id);
